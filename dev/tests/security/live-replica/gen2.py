import json,re
d=json.load(open('/tmp/claude-0/sec/pass2/catalog2.json'))
out=[];w=out.append
w("drop table if exists public.suspensions cascade;")
w("set check_function_bodies = off;")
w("create extension if not exists pgcrypto;")
w("create schema if not exists storage; create schema if not exists extensions;")
w("create table storage.buckets (id text primary key, public boolean);")
w("create table storage.objects (id uuid default gen_random_uuid() primary key, bucket_id text, name text, owner uuid, created_at timestamptz default now());")
w("alter table storage.objects enable row level security;")
w("create or replace function storage.foldername(name text) returns text[] language sql immutable as $$ select (string_to_array(name,'/'))[1:array_length(string_to_array(name,'/'),1)-1] $$;")
w("grant usage on schema storage to anon, authenticated; grant select, insert, update, delete on storage.objects to anon, authenticated;")
w("create or replace function auth.jwt() returns jsonb language sql stable as $$ select nullif(current_setting('request.jwt.claims', true), '')::jsonb $$;")
w("create publication supabase_realtime; create schema if not exists cron;")
ty={'ARRAY':'text[]','USER-DEFINED':'text','timestamp with time zone':'timestamptz','timestamp without time zone':'timestamp'}
cols={}
for c in d['columns']: cols.setdefault(c['t'],[]).append(c)
pub=[t for t in d['tables'] if t['s']=='public' and t['k']=='r']
for t in pub:
    cs=[]
    for c in cols.get(t['t'],[]):
        typ=ty.get(c['ty'],c['ty']); dflt=''
        if c['c']=='id' and typ=='uuid': dflt=' default gen_random_uuid() primary key'
        elif c['c']=='id' and typ in ('bigint','integer'): dflt=' generated by default as identity primary key'
        elif c['c'] in ('created_at','updated_at','joined_at','added_at','at'): dflt=' default now()'
        elif c['c']=='helpful': dflt=' default 0'
        elif c['c']=='status' and t['t']=='friend_requests': dflt=" default 'pending'"
        elif c['c']=='status' and t['t']=='reports': dflt=" default 'open'"
        cs.append(f'"{c["c"]}" {typ}{dflt}')
    w(f'create table public."{t["t"]}" ({", ".join(cs)});')
    if t['rls']: w(f'alter table public."{t["t"]}" enable row level security;')
for c in d['checks']:
    t=c['t'].replace('public.','')
    if c['d'].startswith(('PRIMARY KEY','UNIQUE')) and not t.startswith(('storage','auth')):
        if 'id' in c['d'] and c['d'].startswith('PRIMARY KEY (id)'): continue
        w(f'alter table public."{t}" add constraint "{c["n"]}" {c["d"]};')
for f in d['functions']:
    if f['s']=='public' and f.get('def'): w(f['def'].rstrip()+';')
for c in d['checks']:
    t=c['t'].replace('public.','')
    if c['d'].startswith('CHECK'):
        w(f'alter table public."{t}" add constraint "{c["n"]}" {c["d"]};')
for v in d['views']:
    opts=' with (security_invoker=false)' if v['opts'] else ''
    w(f'create view public."{v["v"]}"{opts} as {v["def"]}')
L={'a':'insert','r':'select','w':'update','d':'delete','D':'truncate','x':'references','t':'trigger'}
for t in d['tables']:
    if t['s']!='public': continue
    w(f'revoke all on public."{t["t"]}" from public, anon, authenticated, service_role;')
    for ent in (t['acl'] or '').strip('{}').split(','):
        if '=' not in ent: continue
        role,rest=ent.split('=',1); privs=rest.split('/')[0]
        if role not in ('anon','authenticated','service_role'): continue
        ps=[L[ch] for ch in privs if ch in L]
        if ps: w(f'grant {", ".join(ps)} on public."{t["t"]}" to {role};')
for g in d['col_grants']:
    if g['s']=='public' and g['p'] in ('SELECT','INSERT','UPDATE','REFERENCES') and g['g']!='PUBLIC':
        w(f'grant {g["p"].lower()} ("{g["c"]}") on public."{g["t"]}" to {g["g"]};')
for f in d['functions']:
    if f['s']!='public': continue
    sig=f['f']
    w(f'revoke all on function public.{sig} from public, anon, authenticated;')
    for ent in (f['acl'] or '{=X/postgres}').strip('{}').split(','):
        role=ent.split('=')[0]
        if role=='': w(f'grant execute on function public.{sig} to public;')
        elif role in ('anon','authenticated','service_role'): w(f'grant execute on function public.{sig} to {role};')
for p in d['policies']:
    if p['s'] not in ('public','storage') or (p['s']=='storage' and p['t']!='objects'): continue
    roles=p['roles'].strip('{}')
    s=f'create policy "{p["n"]}" on {p["s"]}."{p["t"]}" as {p["perm"].lower()} for {p["cmd"].lower()} to {roles}'
    if p['qual']: s+=f' using ({p["qual"]})'
    if p['check']: s+=f' with check ({p["check"]})'
    w(s+';')
for t in d['triggers']:
    tt=t['t']
    if tt.startswith(('storage.','auth.','realtime.')): continue
    if re.search(r'push|seat|email|net\.|alert',t['def']): continue
    w(t['def']+';')
for r in d['realtime']:
    w(f'alter publication supabase_realtime add table public."{r["t"]}";')
open('replica.sql','w').write('\n'.join(out))
print(len(out))
