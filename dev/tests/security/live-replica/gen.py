import json,re,sys
d=json.load(open('/tmp/claude-0/sec/live/catalog-live.json'))
out=[]
w=out.append
w("set check_function_bodies = off;")
w("create extension if not exists pgcrypto;")
w("create schema if not exists extensions; create schema if not exists net; create schema if not exists vault;")
w("create or replace function auth.jwt() returns jsonb language sql stable as $$ select nullif(current_setting('request.jwt.claims', true), '')::jsonb $$;")
w("create or replace function auth.role() returns text language sql stable as $$ select auth.jwt()->>'role' $$;")
w("create or replace function auth.email() returns text language sql stable as $$ select auth.jwt()->>'email' $$;")
ty={'ARRAY':'text[]','USER-DEFINED':'text','timestamp with time zone':'timestamptz','timestamp without time zone':'timestamp'}
cols={}
for c in d['columns']: cols.setdefault(c['t'],[]).append(c)
tables=[t for t in d['tables'] if t['k']=='r']
for t in tables:
    cs=[]
    for c in cols.get(t['t'],[]):
        typ=ty.get(c['ty'],c['ty'])
        dflt=''
        if c['c']=='id' and typ=='uuid': dflt=' default gen_random_uuid() primary key'
        elif c['c']=='id' and typ in ('bigint','integer'): dflt=' generated by default as identity primary key'
        elif c['c'] in ('created_at','updated_at','joined_at','added_at'): dflt=' default now()'
        elif c['c']=='helpful': dflt=' default 0'
        elif c['c']=='status' and t['t']=='friend_requests': dflt=" default 'pending'"
        elif c['c']=='status' and t['t']=='reports': dflt=" default 'open'"
        cs.append(f'"{c["c"]}" {typ}{dflt}')
    w(f'create table public."{t["t"]}" ({", ".join(cs)});')
    if t['rls']: w(f'alter table public."{t["t"]}" enable row level security;')
# unique keys needed for on conflict / membership
w("alter table public.blocks add primary key (blocker, blocked);")
w("alter table public.conversation_members add primary key (conversation_id, user_id);")
w("alter table public.group_members add primary key (group_id, user_id);")
# functions
for f in d['functions']:
    w(f['def'].rstrip()+';')
# views
for v in d['views']:
    opts=' with (security_invoker=false)' if v['opts'] else ''
    w(f'create view public."{v["v"]}"{opts} as {v["def"]}')
# grants
L={'a':'insert','r':'select','w':'update','d':'delete','D':'truncate','x':'references','t':'trigger'}
for t in d['tables']:
    w(f'revoke all on public."{t["t"]}" from public, anon, authenticated, service_role;')
    for ent in (t['acl'] or '').strip('{}').split(','):
        if '=' not in ent: continue
        role,rest=ent.split('=',1); privs=rest.split('/')[0]
        if role not in ('anon','authenticated','service_role'): continue
        ps=[L[ch] for ch in privs if ch in L]
        if ps: w(f'grant {", ".join(ps)} on public."{t["t"]}" to {role};')
for g in d['col_grants']:
    if g['p'] in ('SELECT','INSERT','UPDATE','REFERENCES'):
        w(f'grant {g["p"].lower()} ("{g["c"]}") on public."{g["t"]}" to {g["g"]};')
for f in d['functions']:
    sig=f['f']
    w(f'revoke all on function public.{sig.split("(",1)[0]}({sig.split("(",1)[1]} from public, anon, authenticated;' if not sig.startswith('public.') else '')
    for ent in (f['acl'] or '{=X/postgres}').strip('{}').split(','):
        role=ent.split('=')[0]
        if role=='' : w(f'grant execute on function public.{sig} to public;')
        elif role in ('anon','authenticated','service_role'): w(f'grant execute on function public.{sig} to {role};')
# policies
for p in d['policies']:
    if p['s']!='public': continue
    roles=p['roles'].strip('{}')
    s=f'create policy "{p["n"]}" on public."{p["t"]}" as {p["perm"].lower()} for {p["cmd"].lower()} to {roles}'
    if p['qual']: s+=f' using ({p["qual"]})'
    if p['check']: s+=f' with check ({p["check"]})'
    w(s+';')
# triggers: skip push/net/http ones
for t in d['triggers']:
    if t['t'].startswith('public.') or '.' not in t['t']:
        if re.search(r'push|seat|alert|email|net\.',t['def']): continue
        w(t['def']+';')
open('replica.sql','w').write('\n'.join(x for x in out if x))
print(len(out))
